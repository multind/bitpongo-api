CREATE TABLE fng_strategy (
    id INT NOT NULL AUTO_INCREMENT,
    user_id INT NOT NULL,
    name VARCHAR(100) NOT NULL,
    exchange VARCHAR(64) NOT NULL,
    symbol VARCHAR(32) NOT NULL,
    upper_limit_value INT NOT NULL,
    upper_limit_interval INT NOT NULL,
    lower_limit_value INT NOT NULL,
    lower_limit_interval INT NOT NULL,
    basic_amount DECIMAL(36,18) NOT NULL,
    increase_ratio DECIMAL(36,18) NOT NULL,
    leverage INT NOT NULL,
    bureau_period INT NOT NULL,
    direction VARCHAR(8) NOT NULL,
    start_order_type VARCHAR(8) NOT NULL,
    profit_target_percent DECIMAL(36,18) NOT NULL,
    profit_drawdown_percent DECIMAL(36,18) NOT NULL,
    profit_target_type VARCHAR(16) NOT NULL,
    max_orders INT NOT NULL,
    max_positions INT NOT NULL,
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    valid_from DATETIME(6) NOT NULL,
    last_observed_at DATETIME(6) NULL,
    created_at DATETIME(6) NOT NULL,
    updated_at DATETIME(6) NOT NULL,
    PRIMARY KEY (id),
    KEY ix_fng_strategy_user (user_id),
    KEY ix_fng_strategy_active (enabled),
    CONSTRAINT fk_fng_strategy_user FOREIGN KEY(user_id) REFERENCES user(id) ON DELETE CASCADE
) ENGINE=InnoDB;