-- Futures positions opened by F&G strategies. Monetary values are in USDT.
CREATE TABLE fng_position (
    id BIGINT NOT NULL AUTO_INCREMENT,
    strategy_id INT NOT NULL,
    user_id INT NOT NULL,
    exchange_id INT NOT NULL,
    symbol VARCHAR(32) NOT NULL,
    side VARCHAR(8) NOT NULL,
    status VARCHAR(16) NOT NULL,
    entry_client_order_id VARCHAR(64) NOT NULL,
    exit_client_order_id VARCHAR(64) NULL,
    margin DECIMAL(36,18) NOT NULL,
    quantity DECIMAL(36,18) NOT NULL DEFAULT 0,
    entry_price DECIMAL(36,18) NULL,
    leverage INT NOT NULL,
    peak_profit_percent DECIMAL(36,18) NOT NULL DEFAULT 0,
    close_reason VARCHAR(32) NULL,
    last_error VARCHAR(128) NULL,
    opened_at DATETIME(6) NOT NULL,
    closed_at DATETIME(6) NULL,
    updated_at DATETIME(6) NOT NULL,
    PRIMARY KEY (id),
    UNIQUE KEY uk_fng_entry_client (entry_client_order_id),
    UNIQUE KEY uk_fng_exit_client (exit_client_order_id),
    KEY ix_fng_position_strategy (strategy_id, status),
    KEY ix_fng_position_status (status),
    CONSTRAINT fk_fng_position_strategy FOREIGN KEY (strategy_id) REFERENCES fng_strategy(id) ON DELETE CASCADE,
    CONSTRAINT fk_fng_position_user FOREIGN KEY (user_id) REFERENCES user(id) ON DELETE CASCADE
) ENGINE=InnoDB;